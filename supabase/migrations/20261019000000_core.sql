-- AIOA core schema: companies, members, staff, tickets, messages, events, transcripts.
-- Access is decided by the signed-in e-mail:
--   * e-mail in `staff`   -> support team ("Membro Tech"): sees and edits everything;
--   * e-mail in `members` -> customer user: sees only their company, never internal notes.

-- ---------- tables ----------
create table public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  short text not null,
  contact text not null default '',
  email text not null default '',
  phone text not null default '',
  city text not null default '',
  since text not null default '',
  systems text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table public.members (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies on delete cascade,
  name text not null,
  email text not null,
  role text not null default 'Usuário',
  since timestamptz not null default now()
);
create unique index members_email_key on public.members (lower(email));

create table public.staff (
  email text primary key,
  name text not null,
  role text not null default 'Analista de suporte'
);

create table public.tickets (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies on delete cascade,
  title text not null,
  description text not null default '',
  system text not null,
  category text not null,
  subcategory text not null default '',
  priority text not null default 'Média',
  status text not null default 'Aberto',
  assignee text,
  closed_by text,
  requester text not null,
  tasks jsonb not null default '[]',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index tickets_company_idx on public.tickets (company_id);

-- Append-only: concurrent replies never overwrite each other.
create table public.messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets on delete cascade,
  author text not null,
  body text not null default '',
  via text,
  internal boolean not null default false,
  -- [{ name, type, size, path }] — files live in the `attachments` bucket
  files jsonb not null default '[]',
  created_at timestamptz not null default now()
);
create index messages_ticket_idx on public.messages (ticket_id, created_at);

create table public.ticket_events (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets on delete cascade,
  text text not null,
  created_at timestamptz not null default now()
);
create index ticket_events_ticket_idx on public.ticket_events (ticket_id, created_at);

-- Full transcripts (.txt and .html) are files in the `transcripts` bucket; this row is the index.
create table public.transcripts (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets on delete cascade,
  company_id uuid not null references public.companies on delete cascade,
  code text not null,
  title text not null,
  system text not null,
  requester text not null,
  assignee text,
  closed_by text not null,
  txt_path text,
  html_path text,
  created_at timestamptz not null default now()
);

-- ---------- who is signed in ----------
create function public.my_email() returns text language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''))
$$;

create function public.is_staff() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from staff where lower(email) = my_email())
$$;

create function public.my_company() returns uuid language sql stable security definer set search_path = public as $$
  select company_id from members where lower(email) = my_email() limit 1
$$;

create function public.can_see_ticket(t bigint) returns boolean language sql stable security definer set search_path = public as $$
  select is_staff() or exists (select 1 from tickets where id = t and company_id = my_company())
$$;

-- ---------- row level security ----------
alter table public.companies enable row level security;
alter table public.members enable row level security;
alter table public.staff enable row level security;
alter table public.tickets enable row level security;
alter table public.messages enable row level security;
alter table public.ticket_events enable row level security;
alter table public.transcripts enable row level security;

create policy "companies: staff all" on public.companies for all using (is_staff()) with check (is_staff());
create policy "companies: member reads own" on public.companies for select using (id = my_company());

create policy "members: staff all" on public.members for all using (is_staff()) with check (is_staff());
create policy "members: member reads own company" on public.members for select using (company_id = my_company());

-- Everyone signed in reads the team list (customers need it to tell support replies apart); only staff edit it.
create policy "staff: signed-in reads" on public.staff for select using (auth.role() = 'authenticated');
create policy "staff: staff edits" on public.staff for all using (is_staff()) with check (is_staff());

create policy "tickets: staff all" on public.tickets for all using (is_staff()) with check (is_staff());
create policy "tickets: member reads own company" on public.tickets for select using (company_id = my_company());
create policy "tickets: member opens for own company" on public.tickets for insert with check (company_id = my_company());
-- ponytail: customers may update their company's tickets (a reply reopens it); restrict columns with a trigger if needed.
create policy "tickets: member updates own company" on public.tickets for update using (company_id = my_company()) with check (company_id = my_company());

create policy "messages: staff all" on public.messages for all using (is_staff()) with check (is_staff());
create policy "messages: member reads public" on public.messages for select using (not internal and can_see_ticket(ticket_id));
create policy "messages: member writes public" on public.messages for insert with check (not internal and can_see_ticket(ticket_id));

create policy "events: staff all" on public.ticket_events for all using (is_staff()) with check (is_staff());
create policy "events: member reads" on public.ticket_events for select using (can_see_ticket(ticket_id));
create policy "events: member writes" on public.ticket_events for insert with check (can_see_ticket(ticket_id));

create policy "transcripts: staff all" on public.transcripts for all using (is_staff()) with check (is_staff());
create policy "transcripts: member reads own company" on public.transcripts for select using (company_id = my_company());

-- ---------- realtime ----------
alter publication supabase_realtime add table public.tickets, public.messages, public.ticket_events, public.transcripts;

-- ---------- storage ----------
-- Paths: attachments/<company_id>/<ticket_id>/<file>   transcripts/<company_id>/<ticket_id>/<file>
insert into storage.buckets (id, name, public, file_size_limit)
values ('attachments', 'attachments', false, 10485760), ('transcripts', 'transcripts', false, 10485760);

create policy "attachments: staff all" on storage.objects for all
  using (bucket_id = 'attachments' and public.is_staff()) with check (bucket_id = 'attachments' and public.is_staff());
create policy "attachments: member own company" on storage.objects for select
  using (bucket_id = 'attachments' and (storage.foldername(name))[1] = public.my_company()::text);
create policy "attachments: member uploads own company" on storage.objects for insert
  with check (bucket_id = 'attachments' and (storage.foldername(name))[1] = public.my_company()::text);
-- Transcript files include internal notes: team only. Customers get an HTML export built from what they can see.
create policy "transcripts: staff all" on storage.objects for all
  using (bucket_id = 'transcripts' and public.is_staff()) with check (bucket_id = 'transcripts' and public.is_staff());
