// Generates supabase/seed.sql from the prototype's demo data (companies, members, team, tickets).
// Run: npx tsx scripts/seed-supabase.ts
import { writeFileSync } from 'node:fs';
import { AGENTS, seed, staffEmail } from '../src/app/data';

const q = (v: unknown) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const ts = (ms?: number) => (ms == null ? 'null' : `to_timestamp(${ms / 1000})`);
const arr = (xs: string[]) => `array[${xs.map(q).join(',')}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const db = seed();
const out: string[] = ['-- Generated by scripts/seed-supabase.ts — demo data for AIOA.', 'begin;'];

for (const name of AGENTS) out.push(`insert into staff (email, name) values (${q(staffEmail(name))}, ${q(name)}) on conflict do nothing;`);

for (const c of db.customers) {
  out.push(
    `insert into companies (name, short, contact, email, phone, city, since, systems) values (${[c.name, c.short, c.contact, c.email, c.phone, c.city, c.since].map(q).join(', ')}, ${arr(c.systems)});`,
  );
  for (const m of c.members)
    out.push(`insert into members (company_id, name, email, role, since) select id, ${q(m.name)}, ${q(m.email)}, ${q(m.role)}, ${ts(m.since)} from companies where name = ${q(c.name)};`);
}

for (const t of db.tickets) {
  out.push(
    `insert into tickets (id, company_id, title, description, system, category, subcategory, priority, status, assignee, closed_by, requester, tasks, created_at, updated_at, resolved_at) ` +
      `select ${t.id}, id, ${[t.title, t.description, t.system, t.category, t.subcategory, t.priority, t.status, t.assignee, t.closedBy, t.requester].map(q).join(', ')}, ` +
      `${json(t.tasks)}, ${ts(t.createdAt)}, ${ts(t.updatedAt)}, ${ts(t.resolvedAt)} from companies where name = ${q(t.company)};`,
  );
  for (const m of t.messages)
    out.push(`insert into messages (ticket_id, author, body, via, internal, created_at) values (${t.id}, ${q(m.author)}, ${q(m.body)}, ${q(m.via)}, ${!!m.internal}, ${ts(m.at)});`);
  for (const l of t.log) out.push(`insert into ticket_events (ticket_id, text, created_at) values (${t.id}, ${q(l.text)}, ${ts(l.at)});`);
}

for (const tr of db.transcripts)
  out.push(
    `insert into transcripts (ticket_id, company_id, code, title, system, requester, assignee, closed_by, created_at) select ${tr.ticketId}, id, ` +
      `${[tr.code, tr.title, tr.system, tr.requester, tr.assignee, tr.by].map(q).join(', ')}, ${ts(tr.at)} from companies where name = ${q(tr.company)};`,
  );

// Seeded ids are explicit: move the identity past them so new tickets continue the A- sequence.
out.push(`select setval(pg_get_serial_sequence('tickets', 'id'), (select max(id) from tickets));`, 'commit;');
writeFileSync('supabase/seed.sql', out.join('\n') + '\n');
console.log(`supabase/seed.sql: ${db.customers.length} companies, ${db.tickets.length} tickets, ${db.transcripts.length} transcripts`);
